package ru.spmi.mnlz.ui;

import javax.swing.*;
import java.awt.*;

/** Вкладка «Справка»: методика расчёта и инструкция по работе с программой. */
public final class HelpPanel extends JPanel {

    private static final String TEXT = """
            КАЛЬКУЛЯТОР МЕТАЛЛУРГА — СПРАВКА
            ================================

            1. НАЗНАЧЕНИЕ ПРОГРАММЫ
            Программа выполняет расчёт основных параметров машины непрерывного
            литья заготовки (МНЛЗ) и зоны вторичного охлаждения (ЗВО) по методике
            пособия Токового О.К. (разделы 8–10), сохраняет результаты в базу
            данных SQLite и выгружает отчёты в Excel.

            2. ПОРЯДОК РАБОТЫ
            1) Войдите под своей учётной записью (логин и пароль выдаёт администратор).
            2) Откройте вкладку «Расчёт МНЛЗ»: выберите марку стали из справочника,
               задайте садку агрегата M, сечение заготовки B x b, скорость разливки v,
               цикл плавки и кратность. Нажмите «Рассчитать».
            3) Полученные результаты (глубина лунки Lл и другие) используются
               во вкладке «Расчёт ЗВО»: перенесите Lл в поле «Глубина лунки»,
               задайте температурные параметры и параметры охлаждения.
               Температура поверхности на выходе из ЗВО должна быть не ниже 800 °C.
            4) Сохраните расчёты кнопкой «Сохранить в базу» — они появятся
               на вкладке «База данных».
            5) На вкладке «База данных» можно фильтровать историю по сечению,
               искать марки стали в справочнике, просматривать оборудование МНЛЗ,
               экспортировать историю в Excel. Удаление записей доступно
               только администратору.

            3. ОСНОВНЫЕ ФОРМУЛЫ
            Раздел 8 (основные параметры МНЛЗ):
              - Массовая скорость разливки: Gр = B * b * р * v * n (т/мин);
              - Расход заготовки: Gз = B * b * р * v / 60 (кг/с);
              - Глубина жидкой лунки: Lл = v * t / (2 * k) с проверкой по соотношению
                толщины корки и скорости;
              - Радиус машины: R = H, минимальный радиус Rmin подбирается
                по соотношению толщины заготовки и допустимой деформации.

            Раздел 10 (тепловой расчёт ЗВО):
              - Теплосодержание заготовки на входе: iн = Ст*(Тп'+Ткр)/2*дт/(b/2) +
                + дж/(b/2)*(ΔL + (Тп'+Ткр)/2);
              - Теплосодержание на выходе: iк = Ст*(Тп" + Ткр)/2;
              - Средний коэффициент теплоотдачи: ас = Gз*(iн - iк)*1000 / (F*(Тп ср - Тв));
              - Удельный расход воды: g = (ас - а0)/B;
              - Общий расход воды: Gв = g * F, с распределением по большому
                и малому радиусу в соотношении 1 : 0,8;
              - ЗВО делится на три участка (0,2 / 0,6 / 0,2 длины) с шагом роликов
                по рис. 10.4; число форсунок nф = ni * число промежутков.

            4. СОСТАВ БАЗЫ ДАННЫХ
            users — учётные записи (логин, хэш пароля SHA-256 с солью, роль);
            steel_grades — справочник марок (углерод, Ткр, коэффициенты);
            equipment — витрина оборудования МНЛЗ;
            calculations, calc_inputs, calc_results — история расчётов:
            шапка расчёта и списки входных и выходных параметров.

            5. РОЛИ ПОЛЬЗОВАТЕЛЕЙ
            admin — полный доступ, включая удаление записей истории;
            user  — расчёты, сохранение, экспорт;
            guest — просмотр без изменения данных.
            """;

    public HelpPanel() {
        setLayout(new BorderLayout(8, 8));
        setBorder(BorderFactory.createEmptyBorder(8, 8, 8, 8));

        JTextArea area = new JTextArea(TEXT);
        area.setEditable(false);
        area.setLineWrap(true);
        area.setWrapStyleWord(true);
        area.setFont(new Font(Font.MONOSPACED, Font.PLAIN, 13));
        add(new JScrollPane(area), BorderLayout.CENTER);
    }
}
